const BODY_NARROW: &str = r#"
  404
  not found

  [Intro]  [Blog]  [About]
"#;

pub fn render(ctx: &mut FrameCtx<'_>, frame: &mut Frame<'_>, area: Rect) {
    let body = if area.width < 90 {
        BODY_NARROW
    } else {
        BODY_WIDE
    };
    render_page(frame, area, &ctx.router.title(), body);
}
